changes = []
stale_mp3 = []
for q in data["questions"]:
    qid = q["id"]
    for i, c in enumerate(q["choices"]):
        if c["is_correct"]:
            continue
        key = (qid, i)
        if key in OVERRIDES:
            old = c["tts_text"]
            new = OVERRIDES[key]
            if old != new:
                changes.append({"qid": qid, "ci": i+1, "cid": c["choice_id"], "new": new[:60]})
                if not DRY:
                    c["tts_text"] = new
                    # mark audio for deletion
                    mp3 = os.path.join("audio", "ch2-3", qid, f"{c['choice_id']}.mp3")
                    if os.path.exists(mp3):
                        os.remove(mp3)
                        stale_mp3.append(mp3)

print(f"=== {'DRY RUN' if DRY else 'APPLYING'} answer-leak fixes for ch2-3 ===")
print(f"Changes: {len(changes)}, deleted mp3: {len(stale_mp3)}")
for ch in changes[:5]:
    print(f"  {ch['qid']} c{ch['ci']}: {ch['new']}...")
if len(changes) > 5:
    print(f"  ... and {len(changes)-5} more")

if not DRY:
    with open(SRC, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
