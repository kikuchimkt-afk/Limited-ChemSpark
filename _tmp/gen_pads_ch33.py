    qid = q["id"]
    if qid not in PAD_TARGETS:
        continue
    pads[qid] = {}
    for choice in q["choices"]:
        cid = choice["choice_id"]
        suffix = cid.replace(f"{qid}_", "")
        if suffix in PAD_TARGETS[qid]:
            old_tts = choice["tts_text"]
            new_tts = PAD_TARGETS[qid][suffix]
            pads[qid][old_tts] = new_tts

